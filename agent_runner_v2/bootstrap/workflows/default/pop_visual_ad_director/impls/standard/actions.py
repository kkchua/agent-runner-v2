def _verify_duration(video_path: Path, target_seconds: float, tolerance: float):
    """Verify video duration using ffprobe. Returns True/False or None if tool unavailable."""
    ffprobe = _find_executable("ffprobe")
    if not ffprobe:
        # Try video_editor inspect as fallback
        video_editor = _find_executable("video_editor")
        if not video_editor:
            return None  # Cannot verify, skip

        try:
            proc = subprocess.run(
                [video_editor, "inspect", "--input", str(video_path)],
                capture_output=True,
                text=True,
                timeout=30,
            )
            if proc.returncode != 0:
                return None
            # Try to parse duration from output
            match = re.search(r"[Dd]uration[:\s]+([\d.]+)", proc.stdout or "")
            if match:
                actual = float(match.group(1))
                return abs(actual - target_seconds) <= tolerance
            return None
        except Exception:
            return None

    try:
        proc = subprocess.run(
            [
                ffprobe,
                "-v", "error",
                "-show_entries", "format=duration",
                "-of", "default=noprint_wrappers=1:nokey=1",
                str(video_path),
            ],
            capture_output=True,
            text=True,
            timeout=30,
        )
        if proc.returncode != 0:
            return None
        actual = float((proc.stdout or "").strip())
        return abs(actual - target_seconds) <= tolerance
    except (ValueError, OSError, subprocess.TimeoutExpired):
        return None
