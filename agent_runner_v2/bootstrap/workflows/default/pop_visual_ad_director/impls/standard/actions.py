def _extract_section(text: str, pattern: str, flags: int = 0) -> str:
    """Extract section body from a regex pattern. Returns empty string if no match."""
    m = re.search(pattern, text, flags)
    if m:
        return m.group(1).strip()
    return ""


def _extract_inline_value(text: str, pattern: str) -> str:
    """Extract an inline key: value from text. Returns empty string if no match."""
    m = re.search(pattern, text, re.IGNORECASE)
    if m:
        return m.group(1).strip()
    return ""


def _extract_vibe_keywords(text: str) -> list:
    """Extract vibe keywords from text using multiple pattern strategies."""
    # Try section header first
    vibe_block = _extract_section(
        text,
        r"(?:^|\n)#{1,6}\s*(?:Vibe|Vibe\s+Keywords?)\s*\n(.+?)(?=\n#{1,6}\s|\Z)",
        re.DOTALL,
    )
    if not vibe_block:
        vibe_block = _extract_section(
            text,
            r"(?:^|\n)(?:Vibe|Vibe\s+Keywords?)\s*[:\-]?\s*\n(.+?)(?=\n(?:Product|Visual)|\Z)",
            re.DOTALL,
        )
    if not vibe_block:
        vibe_block = _extract_inline_value(text, r"(?:Vibe|Vibe\s+Keywords?)\s*[:]\s*(.+)")

    if not vibe_block:
        return []

    # Split by comma, semicolons, or newlines
    keywords = re.split(r"[,;\n]+", vibe_block)
    return [kw.strip() for kw in keywords if kw.strip()]


