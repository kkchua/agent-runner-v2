def _generate_single_clip(
    *,
    dreamina_cli: str,
    prompt_text: str,
    duration: float,
    aspect_ratio: str,
    clip_path: Path,
    max_retries: int = 2,
) -> dict:
    """Execute dreamina_cli for a single shot with retry logic."""
    last_error = ""
    for attempt in range(max_retries + 1):
        try:
            cmd = [
                dreamina_cli,
                "--prompt", prompt_text,
                "--duration", str(duration),
                "--aspect-ratio", aspect_ratio,
                "--output", str(clip_path),
            ]
            proc = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=300,
            )
            if proc.returncode == 0:
                if clip_path.exists() and clip_path.stat().st_size > 0:
                    shot_match = re.search(r"shot_(\d+)", clip_path.name)
                    return {
                        "shot_number": int(shot_match.group(1)) if shot_match else 0,
                        "clip_path": str(clip_path),
                        "status": "success",
                        "duration_sec": duration,
                    }
                else:
                    last_error = "Output file missing or empty after successful exit"
            else:
                last_error = proc.stderr.strip() if proc.stderr else f"Exit code {proc.returncode}"
        except subprocess.TimeoutExpired:
            last_error = "Subprocess timed out after 300 seconds"
        except OSError as exc:
            last_error = str(exc)

        if attempt < max_retries:
            backoff = 2 ** attempt
            time.sleep(backoff)

    # Extract shot_number from path
    match = re.search(r"shot_(\d+)", clip_path.name)
    shot_num = int(match.group(1)) if match else 0

    return {
        "shot_number": shot_num,
        "clip_path": None,
        "status": "failed",
        "duration_sec": 0,
        "error": last_error,
    }


