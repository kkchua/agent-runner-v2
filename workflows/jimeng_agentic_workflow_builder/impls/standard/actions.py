def _safe_read_json(path: Path) -> tuple[dict[str, Any] | None, str | None]:
    """Read and parse a JSON file, returning (data, error_message)."""
    try:
        raw = path.read_text(encoding="utf-8")
        return json.loads(raw), None
    except json.JSONDecodeError as exc:
        return None, f"JSON parse error in {path.name}: {exc}"
    except OSError as exc:
        return None, f"Read error for {path.name}: {exc}"


def _escape_toml_string(value: str) -> str:
    """Escape a string value for safe inclusion in a TOML file."""
    return (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )


def _extract_frontmatter(content: str) -> tuple[dict[str, Any], str]:
    """Extract YAML frontmatter and body from markdown content.

    Returns (frontmatter_dict, body_text). If no frontmatter found,
    returns ({}, original_content).
    """
    if not content.startswith("---"):
        return {}, content

    end_idx = content.find("---", 3)
    if end_idx == -1:
        return {}, content

    fm_text = content[3:end_idx].strip()
    if not fm_text:
        return {}, content[end_idx + 3:].strip()

    try:
        fm_data = yaml.safe_load(fm_text)
        if not isinstance(fm_data, dict):
            fm_data = {}
    except yaml.YAMLError:
        fm_data = {}

    body = content[end_idx + 3:].strip()
    return fm_data, body


