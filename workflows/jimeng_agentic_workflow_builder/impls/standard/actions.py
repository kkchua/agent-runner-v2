def _generate_workflow_toml(blueprint: dict[str, Any]) -> str:
    """Generate the workflow.toml content from blueprint data."""
    identity = blueprint["workflow_identity"]
    steps = blueprint["steps"]

    lines: list[str] = []

    # [workflow] section
    lines.append("[workflow]")
    lines.append(f'name = "{_escape_toml_string(identity.get("name", ""))}"')
    lines.append(f'version = "{_escape_toml_string(str(identity.get("version", "")))}"')
    lines.append(f'label = "{_escape_toml_string(identity.get("label", ""))}"')
    lines.append(f'description = "{_escape_toml_string(identity.get("description", ""))}"')
    job_prefix = identity.get("job_prefix", "")
    if job_prefix:
        lines.append(f'job_prefix = "{_escape_toml_string(job_prefix)}"')
    wf_type = identity.get("type", "generic")
    lines.append(f'type = "{_escape_toml_string(wf_type)}"')
    if "subtype" in identity and identity["subtype"] is not None:
        lines.append(f'subtype = "{_escape_toml_string(str(identity["subtype"]))}"')
    lines.append("")

    # [[step]] sections
    for idx, step in enumerate(steps):
        lines.append("[[step]]")
        step_name = step.get("step_id", step.get("name", f"step_{idx + 1}"))
        lines.append(f'name = "{_escape_toml_string(step_name)}"')

        step_type = step.get("step_type", step.get("type", "action"))
        lines.append(f'type = "{_escape_toml_string(step_type)}"')

        if step_type == "action":
            action_name = step.get("action_name", step_name)
            lines.append(f'action = "{_escape_toml_string(action_name)}"')
        elif step_type == "prompt":
            prompt_file = step.get("prompt_file", f"{step_name}.md")
            lines.append(f'prompt = "prompts/{_escape_toml_string(prompt_file)}"')
            role_policy = step.get("role_policy", "architect_standard")
            lines.append(f'role_policy = "{_escape_toml_string(role_policy)}"')

        lines.append("")

        # [step.artifacts]
        lines.append("[step.artifacts]")
        required_inputs = step.get("required_inputs", [])
        produces = step.get("produces", [])

        if required_inputs:
            inputs_str = ", ".join(f'"{_escape_toml_string(k)}"' for k in required_inputs)
            lines.append(f"required_inputs = [{inputs_str}]")
        else:
            lines.append("required_inputs = []")

        if produces:
            produces_str = ", ".join(f'"{_escape_toml_string(k)}"' for k in produces)
            lines.append(f"produces = [{produces_str}]")
        else:
            lines.append("produces = []")

        lines.append("")

        # onsuccess chaining
        if idx < len(steps) - 1:
            next_step_name = steps[idx + 1].get("step_id", steps[idx + 1].get("name", f"step_{idx + 2}"))
            lines.append(f'onsuccess = "{_escape_toml_string(next_step_name)}"')
        else:
            lines.append('onsuccess = "step_completion"')

        lines.append("")

    return "\n".join(lines)


def _generate_actions_py(blueprint: dict[str, Any]) -> str:
    """Generate the actions.py content for the target workflow package."""
    steps = blueprint["steps"]
    action_steps = [s for s in steps if s.get("step_type", s.get("type", "")) == "action"]

    lines: list[str] = []
    lines.append('"""Domain actions for auto-generated workflow package."""')
    lines.append("from __future__ import annotations")
    lines.append("")
    lines.append("import json")
    lines.append("from pathlib import Path")
    lines.append("from typing import Any")
    lines.append("")
    lines.append("from agent_runner_v2.action_result import ActionResult")
    lines.append("from agent_runner_v2.workflow_packages.actions import action")
    lines.append("")

    for step in action_steps:
        func_name = step.get("action_name", step.get("step_id", step["name"]))
        description = step.get("description", f"Action: {func_name}")
        required_inputs = step.get("required_inputs", [])
        produces = step.get("produces", [])

        lines.append("")
        lines.append(f'@action("{func_name}")')
        lines.append(f"def {func_name}(*, context, state, step_cfg, project_root):")
        lines.append(f'    """{description}"""')
        lines.append("    project_root = Path(project_root)")
        lines.append("")

        # Input validation
        for inp_key in required_inputs:
            lines.append(f'    {inp_key}_path = context.get("{inp_key}")')
            lines.append(f"    if not {inp_key}_path:")
            lines.append(f"        return ActionResult(")
            lines.append(f'            status="REJECTED",')
            lines.append(f'            remark="{inp_key} path not found in context",')
            lines.append(f"            artifacts={{}},")
            lines.append(f'            reject_code="MISSING_INPUT_PATH",')
            lines.append(f"        )")
            lines.append(f"    {inp_key}_path = Path({inp_key}_path)")
            lines.append("")

        # Output path resolution
        for out_key in produces:
            lines.append(f'    {out_key}_str = context.get("{out_key}")')
            lines.append(f"    if not {out_key}_str:")
            lines.append(f"        return ActionResult(")
            lines.append(f'            status="REJECTED",')
            lines.append(f'            remark="{out_key} output path not found in context",')
            lines.append(f"            artifacts={{}},")
            lines.append(f'            reject_code="MISSING_OUTPUT_PATH",')
            lines.append(f"        )")
            lines.append(f"    {out_key}_path = Path({out_key}_str)")
            lines.append(f"    {out_key}_path.parent.mkdir(parents=True, exist_ok=True)")
            lines.append("")

        lines.append("    # Core logic: read inputs, process, write outputs")
        lines.append("")

        # Build result
        artifacts_items = ", ".join(
            f'"{k}": str({k}_path)' for k in produces
        )
        lines.append("    return ActionResult(")
        lines.append(f'        status="APPROVED",')
        lines.append(f'        remark="Completed {func_name}",')
        lines.append(f"        artifacts={{{artifacts_items}}},")
        lines.append(f"    )")
        lines.append("")

    return "\n".join(lines)


def _generate_prompt_file(step: dict[str, Any], prompt_index: dict[str, Any] | None = None) -> str:
    """Generate a prompt file content for a prompt step."""
    step_id = step.get("step_id", step.get("name", "unknown_step"))
    description = step.get("description", f"Step: {step_id}")
    role_policy = step.get("role_policy", "architect_standard")
    required_inputs = step.get("required_inputs", [])
    produces = step.get("produces", [])

    # Look up enrichment from prompt index if available
    prompt_entry = None
    if prompt_index and "prompt_entries" in prompt_index:
        for entry in prompt_index["prompt_entries"]:
            if entry.get("step_id") == step_id:
                prompt_entry = entry
                break

    lines: list[str] = []
    lines.append(f"# {step_id.replace('_', ' ').title()}")
    lines.append("")
    lines.append("== ROLE ==")
    lines.append("")

    if prompt_entry and prompt_entry.get("role_context"):
        role_ctx = prompt_entry["role_context"]
        lines.append(f"You are an expert workflow architect operating under the {role_policy} role policy.")
        if isinstance(role_ctx, dict):
            if role_ctx.get("description"):
                lines.append(role_ctx["description"])
            if role_ctx.get("responsibilities"):
                lines.append("")
                lines.append("Responsibilities:")
                for resp in role_ctx["responsibilities"]:
                    lines.append(f"- {resp}")
        elif isinstance(role_ctx, str):
            lines.append(role_ctx)
    else:
        lines.append(f"You are an expert workflow architect operating under the {role_policy} role policy.")
        lines.append(f"Your purpose is to accomplish the task described below with precision and completeness.")

    lines.append("")
    lines.append("== INPUT ==")
    lines.append("")
    lines.append("You receive the following artifacts:")
    lines.append("")

    if prompt_entry and prompt_entry.get("input_sections"):
        for section in prompt_entry["input_sections"]:
            placeholder = section.get("artifact_placeholder", "")
            section_name = section.get("section_name", "")
            section_desc = section.get("description", "")
            if placeholder:
                lines.append(f"{section_name}: {{{placeholder}}}")
                if section_desc:
                    lines.append(f"  {section_desc}")
    else:
        for key in required_inputs:
            lines.append(f"- {{{key}}}")

    lines.append("")

    if prompt_entry and prompt_entry.get("instruction_body"):
        lines.append("== TASK ==")
        lines.append("")
        body = prompt_entry["instruction_body"]
        if isinstance(body, str):
            lines.append(body)
        elif isinstance(body, list):
            for item in body:
                lines.append(str(item))
        lines.append("")

    if prompt_entry and prompt_entry.get("validation_checklist"):
        lines.append("== SELF-VALIDATION CHECKLIST ==")
        lines.append("")
        lines.append("Before writing the output, verify every item below:")
        lines.append("")
        for idx, item in enumerate(prompt_entry["validation_checklist"], 1):
            lines.append(f"{idx}. {item}")
        lines.append("")

    lines.append("== OUTPUT ==")
    lines.append("")
    if produces:
        output_key = produces[0]
        lines.append(f"Write the result to: {{{output_key}}}")
    else:
        lines.append("Write the result as specified in the task description.")
    lines.append("")

    if prompt_entry and prompt_entry.get("quality_constraints"):
        lines.append("== CONSTRAINTS ==")
        lines.append("")
        for constraint in prompt_entry["quality_constraints"]:
            lines.append(f"- {constraint}")
        lines.append("")

    return "\n".join(lines)


def _build_readme(blueprint: dict[str, Any]) -> str:
    """Build README.md content from blueprint data."""
    identity = blueprint["workflow_identity"]
    steps = blueprint["steps"]

    lines: list[str] = []

    # Header
    label = identity.get("label", identity.get("name", "Unknown Workflow"))
    lines.append(f"# Workflow: {label}")
    lines.append("")

    # Description
    desc = identity.get("description", "")
    if desc:
        lines.append("## Description")
        lines.append("")
        lines.append(desc)
        lines.append("")

    # Identity metadata
    lines.append("## Identity")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("|-------|-------|")
    lines.append(f"| name | {identity.get('name', '')} |")
    lines.append(f"| version | {identity.get('version', '')} |")
    lines.append(f"| label | {identity.get('label', '')} |")
    lines.append(f"| job_prefix | {identity.get('job_prefix', '')} |")
    lines.append(f"| type | {identity.get('type', '')} |")
    if "subtype" in identity and identity["subtype"] is not None:
        lines.append(f"| subtype | {identity.get('subtype', '')} |")
    lines.append("")

    # Pipeline overview
    lines.append("## Pipeline Overview")
    lines.append("")
    for idx, step in enumerate(steps, 1):
        step_name = step.get("step_id", step.get("name", f"step_{idx}"))
        step_type = step.get("step_type", step.get("type", "unknown"))
        step_desc = step.get("description", "")
        inputs = step.get("required_inputs", [])
        outputs = step.get("produces", [])

        lines.append(f"### Step {idx}: {step_name}")
        lines.append("")
        lines.append(f"- **Type:** {step_type}")
        if step_desc:
            lines.append(f"- **Purpose:** {step_desc}")
        if inputs:
            lines.append(f"- **Inputs:** {', '.join(inputs)}")
        if outputs:
            lines.append(f"- **Outputs:** {', '.join(outputs)}")
        lines.append("")

    # Artifact flow diagram
    lines.append("## Artifact Flow")
    lines.append("")
    lines.append("```")
    for idx, step in enumerate(steps, 1):
        step_name = step.get("step_id", step.get("name", f"step_{idx}"))
        step_type = step.get("step_type", step.get("type", "unknown"))
        inputs = step.get("required_inputs", [])
        outputs = step.get("produces", [])
        lines.append(f"[{step_name}] ({step_type})")
        if inputs:
            lines.append(f"  inputs:  {', '.join(inputs)}")
        if outputs:
            lines.append(f"  outputs: {', '.join(outputs)}")
        if idx < len(steps):
            lines.append("    |")
            lines.append("    v")
    lines.append("```")
    lines.append("")

    # Input requirements
    lines.append("## Input Requirements")
    lines.append("")
    all_input_keys: set[str] = set()
    for step in steps:
        for key in step.get("required_inputs", []):
            all_input_keys.add(key)
    # Subtract all produced keys to find external inputs
    all_produced: set[str] = set()
    for step in steps:
        for key in step.get("produces", []):
            all_produced.add(key)
    external_inputs = all_input_keys - all_produced
    if external_inputs:
        lines.append("| Key | Description |")
        lines.append("|-----|-------------|")
        for key in sorted(external_inputs):
            lines.append(f"| {key} | External input artifact |")
        lines.append("")
    else:
        lines.append("No external input artifacts required.")
        lines.append("")

    # Output artifacts
    lines.append("## Output Artifacts")
    lines.append("")
    lines.append("| Key | Description |")
    lines.append("|-----|-------------|")
    for step in steps:
        for key in step.get("produces", []):
            if key not in all_produced - set(step.get("produces", [])):
                # Only include final outputs (not consumed by later steps)
                pass
    # Show all produced keys
    for key in sorted(all_produced):
        lines.append(f"| {key} | Produced by workflow pipeline |")
    lines.append("")

    # Usage
    lines.append("## Usage")
    lines.append("")
    job_prefix = identity.get("job_prefix", "")
    name = identity.get("name", "")
    lines.append(f"To invoke this workflow, provide the required input artifacts and run with job_prefix `{job_prefix}`.")
    lines.append("")
    lines.append(f"The workflow `{name}` will produce the output artifacts listed above.")
    lines.append("")

    return "\n".join(lines)


