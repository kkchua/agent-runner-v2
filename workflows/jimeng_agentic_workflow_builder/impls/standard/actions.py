@action("parse_jimeng_markdown")
def parse_jimeng_markdown(*, context, state, step_cfg, project_root):
    """Read a JiMeng/Dreamai-style agentic workflow markdown definition file and parse it into structured JSON."""
    project_root = Path(project_root)

    # --- V-PJM-001: Input path validation ---
    input_path_str = context.get("JIMENG_WORKFLOW_FILE")
    if not input_path_str:
        return ActionResult(
            status="REJECTED",
            remark="JIMENG_WORKFLOW_FILE path not found in context",
            artifacts={},
            reject_code="MISSING_INPUT_PATH",
        )

    input_path = Path(input_path_str)

    # --- V-PJM-002: File existence check ---
    if not input_path.is_file():
        return ActionResult(
            status="REJECTED",
            remark=f"JIMENG_WORKFLOW_FILE does not exist: {input_path}",
            artifacts={},
            reject_code="FILE_NOT_FOUND",
        )

    # --- V-PJM-004: Output path validation ---
    output_path_str = context.get("PARSED_JIMENG_FILE")
    if not output_path_str:
        return ActionResult(
            status="REJECTED",
            remark="PARSED_JIMENG_FILE output path not found in context",
            artifacts={},
            reject_code="MISSING_OUTPUT_PATH",
        )
    output_path = Path(output_path_str)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # --- V-PJM-003: Read and decode file ---
    try:
        content = input_path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return ActionResult(
            status="REJECTED",
            remark=f"Cannot decode JIMENG_WORKFLOW_FILE as UTF-8: {input_path}",
            artifacts={},
            reject_code="ENCODING_ERROR",
        )
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to read JIMENG_WORKFLOW_FILE: {exc}",
            artifacts={},
            reject_code="FILE_NOT_FOUND",
        )

    # --- Parse YAML frontmatter ---
    frontmatter, body = _extract_frontmatter(content)

    # --- Split into H2 sections ---
    sections = _split_sections(body)

    # --- Classify and extract from each section ---
    identity_data: dict[str, Any] = {}
    roles: list[dict[str, Any]] = []
    tool_specs: list[dict[str, Any]] = []
    execution_phases: list[dict[str, Any]] = []
    configuration_cards: list[dict[str, Any]] = []
    embedded_prompts: list[dict[str, Any]] = []
    state_variables: list[dict[str, Any]] = []
    conditional_routing: list[dict[str, Any]] = []
    quality_criteria: list[dict[str, Any]] = []
    constraints: list[str] = []

    # Extract identity from frontmatter
    identity_data["name"] = frontmatter.get("name", frontmatter.get("workflow_name", ""))
    identity_data["codename"] = frontmatter.get("codename", frontmatter.get("name", ""))
    identity_data["title"] = frontmatter.get("title", frontmatter.get("label", ""))
    identity_data["type"] = frontmatter.get("type", "")
    identity_data["version"] = str(frontmatter.get("version", ""))
    identity_data["description"] = frontmatter.get("description", "")

    for section in sections:
        heading = section["heading"]
        sec_body = section["body"]
        section_type = _classify_section(heading, sec_body)

        if section_type == "identity":
            # Supplement identity from overview section
            if not identity_data.get("name"):
                name_match = re.search(r"(?:name|workflow|agent)[:\s]+(.+)", sec_body[:500], re.IGNORECASE)
                if name_match:
                    identity_data["name"] = name_match.group(1).strip()

            # Try to extract roles from identity section too
            section_roles = _extract_roles_from_section(sec_body)
            if section_roles:
                roles.extend(section_roles)

        elif section_type == "tool_specs":
            extracted_tools = _extract_tool_specs_from_section(sec_body)
            tool_specs.extend(extracted_tools)

        elif section_type == "execution_phases":
            extracted_phases = _extract_execution_phases(sec_body)
            execution_phases.extend(extracted_phases)

        elif section_type == "configuration_cards":
            extracted_cards = _extract_configuration_cards(sec_body)
            configuration_cards.extend(extracted_cards)

        elif section_type == "embedded_prompts":
            extracted_prompts = _extract_embedded_prompts(sec_body)
            embedded_prompts.extend(extracted_prompts)

        elif section_type == "state_variables":
            extracted_vars = _extract_state_variables(sec_body)
            state_variables.extend(extracted_vars)

        elif section_type == "conditional_routing":
            extracted_rules = _extract_conditional_routing(sec_body)
            conditional_routing.extend(extracted_rules)

        elif section_type == "quality_criteria":
            extracted_criteria = _extract_quality_criteria(sec_body)
            quality_criteria.extend(extracted_criteria)

        elif section_type == "constraints":
            extracted_constraints = _extract_constraints(sec_body)
            constraints.extend(extracted_constraints)

        elif section_type == "general":
            # Try to detect content type from body patterns
            if re.search(r"(?:phase|step)\s*\d+", heading.lower()):
                extracted_phases = _extract_execution_phases(sec_body)
                if extracted_phases:
                    execution_phases.extend(extracted_phases)
            elif "tool" in heading.lower():
                extracted_tools = _extract_tool_specs_from_section(sec_body)
                if extracted_tools:
                    tool_specs.extend(extracted_tools)

    # --- V-PJM-005: Validate identity ---
    if not identity_data.get("name") and not identity_data.get("codename"):
        return ActionResult(
            status="REJECTED",
            remark="Parsed JSON has empty identity (no name/codename found)",
            artifacts={},
            reject_code="MISSING_IDENTITY",
        )

    # --- V-PJM-006: Validate non-empty workflow ---
    if not execution_phases and not configuration_cards and not tool_specs:
        return ActionResult(
            status="REJECTED",
            remark="Parsed JSON has zero execution_phases, zero configuration_cards, and zero tool_specs",
            artifacts={},
            reject_code="EMPTY_WORKFLOW",
        )

    # --- Assemble output JSON ---
    parsed_output = {
        "identity": identity_data,
        "roles": roles,
        "tool_specs": tool_specs,
        "execution_phases": execution_phases,
        "configuration_cards": configuration_cards,
        "embedded_prompts": embedded_prompts,
        "state_variables": state_variables,
        "conditional_routing": conditional_routing,
        "quality_criteria": quality_criteria,
        "constraints": constraints,
    }

    # --- Serialize and write output ---
    try:
        json_str = json.dumps(parsed_output, indent=2, ensure_ascii=False)
    except (TypeError, ValueError) as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to serialize parsed output to JSON: {exc}",
            artifacts={},
            reject_code="SERIALIZATION_ERROR",
        )

    try:
        output_path.write_text(json_str, encoding="utf-8")
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to write PARSED_JIMENG_FILE: {exc}",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    # --- V-PJM-007/V-PJM-008: Verify output file ---
    if not output_path.is_file():
        return ActionResult(
            status="REJECTED",
            remark="PARSED_JIMENG_FILE was not created on disk",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )
    if output_path.stat().st_size == 0:
        return ActionResult(
            status="REJECTED",
            remark="PARSED_JIMENG_FILE was created but is empty (0 bytes)",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    return ActionResult(
        status="APPROVED",
        remark=(
            f"Parsed JiMeng markdown: {len(roles)} roles, {len(tool_specs)} tools, "
            f"{len(execution_phases)} phases, {len(configuration_cards)} config cards, "
            f"{len(embedded_prompts)} embedded prompts, {len(state_variables)} state vars, "
            f"{len(conditional_routing)} routing rules, {len(quality_criteria)} quality criteria, "
            f"{len(constraints)} constraints"
        ),
        artifacts={"PARSED_JIMENG_FILE": str(output_path)},
    )


@action("assemble_workflow_package")
def assemble_workflow_package(*, context, state, step_cfg, project_root):
    """Assemble the complete executable agent-runner-v2 workflow package directory from the workflow blueprint and prompt template specifications."""
    project_root = Path(project_root)

    # --- V-AWP-001: WORKFLOW_BLUEPRINT_FILE input ---
    blueprint_path_str = context.get("WORKFLOW_BLUEPRINT_FILE")
    if not blueprint_path_str:
        return ActionResult(
            status="REJECTED",
            remark="WORKFLOW_BLUEPRINT_FILE path not found in context",
            artifacts={},
            reject_code="MISSING_INPUT_PATH",
        )
    blueprint_path = Path(blueprint_path_str)
    if not blueprint_path.is_file():
        return ActionResult(
            status="REJECTED",
            remark=f"WORKFLOW_BLUEPRINT_FILE does not exist: {blueprint_path}",
            artifacts={},
            reject_code="MISSING_INPUT_PATH",
        )

    # --- V-AWP-002: PROMPT_TEMPLATES_FILE input ---
    prompts_path_str = context.get("PROMPT_TEMPLATES_FILE")
    if not prompts_path_str:
        return ActionResult(
            status="REJECTED",
            remark="PROMPT_TEMPLATES_FILE path not found in context",
            artifacts={},
            reject_code="MISSING_INPUT_PATH",
        )
    prompts_path = Path(prompts_path_str)
    if not prompts_path.is_file():
        return ActionResult(
            status="REJECTED",
            remark=f"PROMPT_TEMPLATES_FILE does not exist: {prompts_path}",
            artifacts={},
            reject_code="MISSING_INPUT_PATH",
        )

    # --- Parse JSON inputs ---
    blueprint_data, bp_err = _safe_read_json(blueprint_path)
    if bp_err is not None or blueprint_data is None:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to parse WORKFLOW_BLUEPRINT_FILE: {bp_err}",
            artifacts={},
            reject_code="INVALID_JSON_INPUT",
        )

    prompt_data, pt_err = _safe_read_json(prompts_path)
    if pt_err is not None or prompt_data is None:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to parse PROMPT_TEMPLATES_FILE: {pt_err}",
            artifacts={},
            reject_code="INVALID_JSON_INPUT",
        )

    # --- V-AWP-003: Validate blueprint schema ---
    if "workflow_identity" not in blueprint_data or "steps" not in blueprint_data:
        return ActionResult(
            status="REJECTED",
            remark="WORKFLOW_BLUEPRINT_FILE missing required top-level keys: workflow_identity, steps",
            artifacts={},
            reject_code="MALFORMED_INPUT_SCHEMA",
        )

    # --- V-AWP-004: Validate prompt templates schema ---
    if "prompt_entries" not in prompt_data:
        return ActionResult(
            status="REJECTED",
            remark="PROMPT_TEMPLATES_FILE missing required top-level key: prompt_entries",
            artifacts={},
            reject_code="MALFORMED_INPUT_SCHEMA",
        )

    # --- V-AWP-005: Steps list non-empty ---
    steps = blueprint_data.get("steps", [])
    if not steps:
        return ActionResult(
            status="REJECTED",
            remark="WORKFLOW_BLUEPRINT_FILE contains no step definitions",
            artifacts={},
            reject_code="EMPTY_STEP_LIST",
        )

    # --- V-AWP-006: Cross-validate prompt steps ---
    prompt_steps = [s for s in steps if s.get("step_type", s.get("type", "")) == "prompt"]
    prompt_entries = prompt_data.get("prompt_entries", [])
    prompt_step_ids = {s.get("step_id", s.get("name")) for s in prompt_steps}
    indexed_step_ids = {e.get("step_id") for e in prompt_entries}

    missing_prompt_entries = prompt_step_ids - indexed_step_ids
    if missing_prompt_entries:
        return ActionResult(
            status="REJECTED",
            remark=f"Prompt steps missing from PROMPT_TEMPLATES_FILE: {sorted(missing_prompt_entries)}",
            artifacts={},
            reject_code="PROMPT_INDEX_MISMATCH",
        )

    # --- V-AWP-007/V-AWP-008: Output paths ---
    package_dir_str = context.get("WORKFLOW_PACKAGE_DIR")
    if not package_dir_str:
        return ActionResult(
            status="REJECTED",
            remark="WORKFLOW_PACKAGE_DIR output path not found in context",
            artifacts={},
            reject_code="MISSING_OUTPUT_PATH",
        )
    package_dir = Path(package_dir_str)

    readme_path_str = context.get("WORKFLOW_README_FILE")
    if not readme_path_str:
        return ActionResult(
            status="REJECTED",
            remark="WORKFLOW_README_FILE output path not found in context",
            artifacts={},
            reject_code="MISSING_OUTPUT_PATH",
        )
    readme_path = Path(readme_path_str)

    # --- Create directory structure ---
    try:
        package_dir.mkdir(parents=True, exist_ok=True)
        (package_dir / "prompts").mkdir(parents=True, exist_ok=True)
        (package_dir / "impls" / "standard").mkdir(parents=True, exist_ok=True)
        (package_dir / "impls" / "standard" / "prompts").mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to create package directory structure: {exc}",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    # --- Generate workflow.toml ---
    try:
        toml_content = _generate_workflow_toml(blueprint_data)
        (package_dir / "workflow.toml").write_text(toml_content, encoding="utf-8")
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to write workflow.toml: {exc}",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    # --- Generate actions.py ---
    try:
        actions_content = _generate_actions_py(blueprint_data)
        (package_dir / "actions.py").write_text(actions_content, encoding="utf-8")
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to write actions.py: {exc}",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    # --- Generate prompt files ---
    try:
        prompts_dir = package_dir / "impls" / "standard" / "prompts"
        for step in prompt_steps:
            step_id = step.get("step_id", step.get("name", "unknown"))
            prompt_file_name = step.get("prompt_file", f"{step_id}.md")
            prompt_content = _generate_prompt_file(step, prompt_data)
            (prompts_dir / prompt_file_name).write_text(prompt_content, encoding="utf-8")
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to write prompt files: {exc}",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    # --- Generate impls/standard/impl.yaml ---
    try:
        impl_yaml_content = _generate_impl_yaml(blueprint_data)
        (package_dir / "impls" / "standard" / "impl.yaml").write_text(impl_yaml_content, encoding="utf-8")
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to write impl.yaml: {exc}",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    # --- Generate requirements.txt ---
    try:
        req_content = "# No external dependencies required -- all imports are from the Python standard library.\n"
        (package_dir / "requirements.txt").write_text(req_content, encoding="utf-8")
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to write requirements.txt: {exc}",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    # --- Generate README.md ---
    try:
        readme_content = _build_readme(blueprint_data)
        readme_path.parent.mkdir(parents=True, exist_ok=True)
        readme_path.write_text(readme_content, encoding="utf-8")
    except OSError as exc:
        return ActionResult(
            status="REJECTED",
            remark=f"Failed to write README.md: {exc}",
            artifacts={},
            reject_code="WRITE_FAILURE",
        )

    # --- V-AWP-009: Verify all expected files exist ---
    expected_files = [
        package_dir / "workflow.toml",
        package_dir / "actions.py",
        package_dir / "requirements.txt",
        package_dir / "impls" / "standard" / "impl.yaml",
    ]

    impls_prompts_dir = package_dir / "impls" / "standard" / "prompts"
    prompt_files_written = list(impls_prompts_dir.iterdir()) if impls_prompts_dir.is_dir() else []
    expected_files.extend([f for f in prompt_files_written if f.is_file()])

    missing = [f for f in expected_files if not f.is_file()]
    if missing:
        return ActionResult(
            status="REJECTED",
            remark=f"Expected files not found after write: {[str(f) for f in missing]}",
            artifacts={},
            reject_code="INCOMPLETE_PACKAGE",
        )

    # --- V-AWP-010: Verify README exists and is non-empty ---
    if not readme_path.is_file():
        return ActionResult(
            status="REJECTED",
            remark="README.md was not created",
            artifacts={},
            reject_code="INCOMPLETE_PACKAGE",
        )
    if readme_path.stat().st_size == 0:
        return ActionResult(
            status="REJECTED",
            remark="README.md was created but is empty",
            artifacts={},
            reject_code="INCOMPLETE_PACKAGE",
        )

    return ActionResult(
        status="APPROVED",
        remark=(
            f"Workflow package assembled at {package_dir} with {len(steps)} steps, "
            f"{len(prompt_files_written)} prompt files, and README"
        ),
        artifacts={
            "WORKFLOW_PACKAGE_DIR": str(package_dir),
            "WORKFLOW_README_FILE": str(readme_path),
        },
    )


def _generate_impl_yaml(blueprint: dict[str, Any]) -> str:
    """Generate impl.yaml content for the standard implementation."""
    identity = blueprint.get("workflow_identity", {})
    wf_name = identity.get("name", "workflow")
    steps = blueprint.get("steps", [])

    lines: list[str] = []
    lines.append("name: standard")
    lines.append(f'description: "Default implementation for {wf_name}"')
    lines.append('label: "Standard"')
    lines.append("")

    # Add overrides if there are prompt steps
    has_overrides = False
    for step in steps:
        step_type = step.get("step_type", step.get("type", "action"))
        if step_type == "prompt":
            if not has_overrides:
                lines.append("overrides:")
                has_overrides = True
            step_id = step.get("step_id", step.get("name", "unknown"))
            prompt_file = step.get("prompt_file", f"{step_id}.md")
            lines.append(f"  {step_id}:")
            lines.append(f"    prompt: prompts/{prompt_file}")

    return "\n".join(lines)
