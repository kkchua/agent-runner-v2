def _parse_markdown_table(text: str) -> list[dict[str, str]]:
    """Parse markdown table rows into list-of-dicts keyed by header names."""
    lines = [l.strip() for l in text.strip().splitlines() if l.strip()]
    if len(lines) < 2:
        return []

    header_line = lines[0]
    if "|" not in header_line:
        return []

    headers = [h.strip() for h in header_line.split("|") if h.strip()]
    if not headers:
        return []

    rows: list[dict[str, str]] = []
    for line in lines[1:]:
        # Skip separator rows like |---|---|
        if re.match(r"^\|[\s\-:|]+\|$", line):
            continue
        if "|" not in line:
            continue

        cells = [c.strip() for c in line.split("|")]
        # Filter empty leading/trailing cells from split
        cells = [c for c in cells if c != "" or len(cells) <= len(headers)]
        # Remove leading/trailing empty strings from split
        while cells and cells[0] == "":
            cells.pop(0)
        while cells and cells[-1] == "":
            cells.pop()

        row: dict[str, str] = {}
        for i, header in enumerate(headers):
            row[header] = cells[i].strip() if i < len(cells) else ""
        rows.append(row)

    return rows


