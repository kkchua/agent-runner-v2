def _resolve_package_path(relative_path: str) -> str:
    """Convert a relative file path to a Python package path.

    E.g. 'agent_runner_v2/workflow/__init__.py' -> 'agent_runner_v2.workflow'
    E.g. 'agent_runner_v2/workflow/runner.py' -> 'agent_runner_v2.workflow.runner'
    """
    p = Path(relative_path)
    parts = list(p.parts)
    if parts[-1] == "__init__.py":
        parts = parts[:-1]
    else:
        parts[-1] = parts[-1].rsplit(".py", 1)[0]
    return ".".join(parts)


def _resolve_relative_import(
    level: int,
    import_module: str | None,
    file_package: str,
) -> str | None:
    """Resolve a relative import to an absolute module name.

    Args:
        level: Number of leading dots (1 for '.', 2 for '..', etc.)
        import_module: The module portion after 'from .X import' (can be None)
        file_package: The fully qualified package of the importing file

    Returns:
        Fully qualified module name, or None if unresolvable.
    """
    parts = file_package.split(".")
    # level=1 means relative to current package
    # level=2 means relative to parent package, etc.
    go_up = level - 1
    if go_up > len(parts):
        return None
    if go_up > 0:
        base_parts = parts[:-go_up]
    else:
        base_parts = parts[:]

    base = ".".join(base_parts)
    if import_module:
        if base:
            return f"{base}.{import_module}"
        return import_module
    return base if base else None


def _detect_cycles(adjacency: dict[str, list[str]]) -> list[list[str]]:
    """Detect all unique cycles in a directed graph using DFS.

    Returns list of cycles, where each cycle is a list of module names
    with the first and last being the same node.
    """
    visited: set[str] = set()
    rec_stack: set[str] = set()
    path: list[str] = []
    cycles: list[list[str]] = []
    seen_cycle_keys: set[str] = set()

    def _dfs(node: str) -> None:
        visited.add(node)
        rec_stack.add(node)
        path.append(node)

        for neighbor in adjacency.get(node, []):
            if neighbor not in visited:
                _dfs(neighbor)
            elif neighbor in rec_stack:
                # Found a cycle - extract it
                cycle_start = path.index(neighbor)
                cycle = path[cycle_start:] + [neighbor]
                # Normalize cycle for dedup: rotate so smallest element is first
                min_idx = cycle[:-1].index(min(cycle[:-1]))
                normalized = cycle[min_idx:-1] + cycle[:min_idx] + [cycle[min_idx]]
                key = "->".join(normalized[:-1])
                if key not in seen_cycle_keys:
                    seen_cycle_keys.add(key)
                    cycles.append(normalized)

        path.pop()
        rec_stack.discard(node)

    for node in sorted(adjacency.keys()):
        if node not in visited:
            _dfs(node)

    return cycles


def _validate_markdown_content(content: str) -> dict[str, Any]:
    """Validate a Markdown file's structure and evidence backing.

    Returns a dict with validation results.
    """
    result = {
        "exists": True,
        "has_headings": False,
        "has_evidence": False,
        "self_contained": True,
    }

    # Check for headings
    heading_pattern = re.compile(r"^#{1,6}\s+.+", re.MULTILINE)
    if heading_pattern.search(content):
        result["has_headings"] = True

    # Check for evidence: file paths, inline code, or fenced code blocks
    file_path_pattern = re.compile(r"[`\"\'](?:[\w./\\-]+\.(?:py|md|json|yaml|toml|txt))")
    inline_code_pattern = re.compile(r"`[^`]+`")
    fenced_code_pattern = re.compile(r"```")

    if (file_path_pattern.search(content)
            or inline_code_pattern.search(content)
            or fenced_code_pattern.search(content)):
        result["has_evidence"] = True

    # Check for self-containment: no dangling references
    dangling_patterns = [
        r"see above(?!.*(?:heading|section|table|figure))",
        r"see previous section",
        r"as mentioned before(?!.*(?:heading|section|table|figure))",
        r"described earlier(?!.*(?:heading|section|table|figure))",
    ]
    for pat in dangling_patterns:
        if re.search(pat, content, re.IGNORECASE):
            result["self_contained"] = False
            break

    return result


