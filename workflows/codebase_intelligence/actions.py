def _read_text_safe(path: Path, max_chars: int | None = None) -> str | None:
    """Read a file as UTF-8 text, falling back to latin-1. Returns None if binary."""
    try:
        text = path.read_text(encoding="utf-8")
        if max_chars is not None:
            return text[:max_chars]
        return text
    except UnicodeDecodeError:
        try:
            text = path.read_text(encoding="latin-1")
            if max_chars is not None:
                return text[:max_chars]
            return text
        except Exception:
            return None
    except OSError:
        return None


def _extract_title_from_markdown(text: str) -> str:
    """Extract the first heading from markdown content."""
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped.startswith("#"):
            return stripped.lstrip("#").strip()
    return ""


def _has_docstring(content: str) -> bool:
    """Check if a Python file has a module-level docstring."""
    try:
        tree = ast.parse(content)
        if tree.body and isinstance(tree.body[0], ast.Expr):
            if isinstance(tree.body[0].value, (ast.Constant,)):
                return isinstance(tree.body[0].value.value, str)
    except SyntaxError:
        pass
    return False


def _is_binary_file(path: Path) -> bool:
    """Heuristic check for binary files."""
    try:
        chunk = path.read_bytes()[:8192]
        if b"\x00" in chunk:
            return True
        return False
    except OSError:
        return True


